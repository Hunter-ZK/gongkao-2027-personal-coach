def _ensure_sources():
    if LEGACY.exists() and any(LEGACY.glob('*.md')):
        return
    if ARCHIVE.exists():
        CONTENT.mkdir(parents=True, exist_ok=True)
        with zipfile.ZipFile(ARCHIVE, 'r') as z:
            z.extractall(CONTENT)


def _clean_md(text):
    text = re.sub(r'<script[\s\S]*?</script>', '', text, flags=re.I)
    text = re.sub(r'<div STYLE="page-break-after: always;"></div>', '', text, flags=re.I)
    text = re.sub(r'<a id=.*?</a>', '', text)
    text = re.sub(r'<img[^>]*>', '> 原笔记此处含配图；当前本地知识库先保留文字规则，后续补入典型图例。', text, flags=re.I)
    text = text.replace('&emsp;', ' ')
    return text.strip()


def _sections(path):
    if not path.exists(): return []
    text = _clean_md(path.read_text('utf-8', errors='ignore'))
    out=[]; current={'title':'导言','level':1,'body':[]}
    for line in text.splitlines():
        m=re.match(r'^(#{1,4})\s+(.+?)\s*$', line)
        if m:
            body='\n'.join(current['body']).strip()
            if body: out.append({'title':current['title'],'level':current['level'],'body':body})
            current={'title':re.sub(r'<[^>]+>','',m.group(2)).strip(),'level':len(m.group(1)),'body':[]}
        else:
            current['body'].append(line)
    body='\n'.join(current['body']).strip()
    if body: out.append({'title':current['title'],'level':current['level'],'body':body})
    return out


def _keywords(title):
    ks = ALIASES.get(title, []) + [title]
    # add semantic chunks so “工程问题-合作” can match “工程问题”
    ks += [x for x in re.split(r'[-—·/（）() ]+',title) if len(x)>=2]
    return list(dict.fromkeys(ks))


def _find_source(module,title,limit=3):
    _ensure_sources()
    ks=_keywords(title)
    hits=[]
    for fn in MODULE_FILES.get(module,[]):
        path=LEGACY/fn
        for sec in _sections(path):
            score=0
            st=sec['title']; body=sec['body']
            for k in ks:
                if k and k in st: score+=12
                if k and k in body: score+=min(5,body.count(k))
            if score:
                hits.append((score,fn,sec))
    hits.sort(key=lambda x:x[0], reverse=True)
    chunks=[]
    seen=set()
    for score,fn,sec in hits:
        key=(fn,sec['title'])
        if key in seen: continue
        seen.add(key)
        body=sec['body']
        if len(body)>4200: body=body[:4200]+'\n\n> （该节内容较长，系统已截取本页最相关部分。）'
        chunks.append(f"### 来自你的旧笔记｜{fn}｜{sec['title']}\n\n{body}")
        if len(chunks)>=limit: break
    return '\n\n---\n\n'.join(chunks)


